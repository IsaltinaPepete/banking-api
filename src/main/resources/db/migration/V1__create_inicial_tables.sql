
-- V1__create_inicial_tables.sql

-- 1. CUSTOMERS

CREATE TABLE customers (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    nuit VARCHAR(20) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ
);

-- 2. APP USERS

CREATE TABLE app_users (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    keycloak_user_id VARCHAR(100) NOT NULL UNIQUE,
    customer_id UUID UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_user_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id)
);

-- 3. BANK ACCOUNTS

CREATE TABLE bank_accounts (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    customer_id UUID NOT NULL,
    account_number VARCHAR(30) NOT NULL UNIQUE,
    account_type VARCHAR(20) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'MZN',
    balance DECIMAL(19,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,

    CONSTRAINT fk_account_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(id),

    CONSTRAINT chk_account_type
        CHECK (account_type IN ('CURRENT', 'SAVINGS')),

    CONSTRAINT chk_account_balance
        CHECK (balance >= 0)
);

-- 4. TRANSACTIONS

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference UUID DEFAULT gen_random_uuid() NOT NULL UNIQUE,
    type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'MZN',
    description VARCHAR(255),
    initiated_by UUID,
    idempotency_key UUID UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,

    CONSTRAINT fk_transaction_user
        FOREIGN KEY (initiated_by)
        REFERENCES app_users(id),

    CONSTRAINT chk_transaction_type
        CHECK (type IN (
            'INITIAL_DEPOSIT',
            'TRANSFER',
            'DEPOSIT',
            'WITHDRAWAL'
        )),

    CONSTRAINT chk_transaction_status
        CHECK (status IN (
            'PENDING',
            'COMPLETED',
            'FAILED',
            'REVERSED'
        )),

    CONSTRAINT chk_transaction_amount
        CHECK (amount > 0)
);

-- 5. TRANSFERS

CREATE TABLE transfers (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    transaction_id BIGINT NOT NULL UNIQUE,
    source_account_id UUID NOT NULL,
    destination_account_id UUID NOT NULL,

    CONSTRAINT fk_transfer_transaction
        FOREIGN KEY (transaction_id)
        REFERENCES transactions(id),

    CONSTRAINT fk_transfer_source
        FOREIGN KEY (source_account_id)
        REFERENCES bank_accounts(id),

    CONSTRAINT fk_transfer_destination
        FOREIGN KEY (destination_account_id)
        REFERENCES bank_accounts(id),

    CONSTRAINT chk_different_accounts
        CHECK (source_account_id <> destination_account_id)
);

-- 6. ACCOUNT MOVEMENTS

CREATE TABLE account_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    account_id UUID NOT NULL,
    direction VARCHAR(10) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    balance_after DECIMAL(19,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_movement_transaction
        FOREIGN KEY (transaction_id)
        REFERENCES transactions(id),

    CONSTRAINT fk_movement_account
        FOREIGN KEY (account_id)
        REFERENCES bank_accounts(id),

    CONSTRAINT chk_movement_direction
        CHECK (direction IN ('DEBIT', 'CREDIT')),

    CONSTRAINT chk_movement_amount
        CHECK (amount > 0),

    CONSTRAINT chk_movement_balance
        CHECK (balance_after >= 0)
);
